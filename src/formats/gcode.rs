use crate::document::Document;
use crate::optimizer::OptimizedJob;

pub struct GCodeConfig {
    pub metric: bool,           // G21
    pub absolute: bool,         // G90
    pub dynamic_power_mode: bool, // M4 for GRBL 1.1+, M3 for legacy
    pub max_s_value: f64,       // 1000.0 for GRBL, 255.0 for older
    pub rapid_speed: f64,       // mm/min
    pub air_assist_on_cmd: String,  // "M8"
    pub air_assist_off_cmd: String, // "M9"
    pub bed_width: f64,
    pub bed_height: f64,
    pub mirror_x: bool,
    pub mirror_y: bool,
}

impl Default for GCodeConfig {
    fn default() -> Self {
        Self {
            metric: true,
            absolute: true,
            dynamic_power_mode: true,
            max_s_value: 1000.0,
            rapid_speed: 6000.0,
            air_assist_on_cmd: "M8".to_string(),
            air_assist_off_cmd: "M9".to_string(),
            bed_width: 400.0,
            bed_height: 400.0,
            mirror_x: false,
            mirror_y: false,
        }
    }
}

pub struct GCodeGenerator {
    pub config: GCodeConfig,
}

impl GCodeGenerator {
    pub fn new(config: GCodeConfig) -> Self {
        Self { config }
    }

    /// Generates G-code string for the optimized toolpath job
    pub fn generate(&self, doc: &Document, job: &OptimizedJob) -> String {
        let mut out = String::new();

        // Header
        out.push_str("; Generated by LaserBurn (Rust)\n");
        out.push_str(&format!("; Document: {}\n", doc.name));
        out.push_str("G21 ; Millimeters\n");
        out.push_str("G90 ; Absolute coordinates\n");
        out.push_str(&format!("G0 F{:.1} ; Set rapid rate\n", self.config.rapid_speed));

        let laser_mode_cmd = if self.config.dynamic_power_mode { "M4" } else { "M3" };

        let mut air_assist_active = false;

        for path in &job.paths {
            let layer = doc.layers.get(&path.layer_index);
            let cut_setting = layer.map(|l| &l.cut_setting);

            let speed_mm_min = cut_setting.map(|cs| cs.speed * 60.0).unwrap_or(3000.0);
            let power_pct = cut_setting.map(|cs| cs.power_max).unwrap_or(80.0);
            let s_val = (power_pct / 100.0 * self.config.max_s_value).clamp(0.0, self.config.max_s_value);
            let air_assist = cut_setting.map(|cs| cs.air_assist).unwrap_or(true);
            let passes = cut_setting.map(|cs| cs.num_passes).unwrap_or(1);
            let z_step = cut_setting.map(|cs| cs.z_step_per_pass).unwrap_or(0.0);
            let mut z_curr = cut_setting.map(|cs| cs.z_offset).unwrap_or(0.0);

            let pts = &path.polyline.points;
            if pts.len() < 2 {
                continue;
            }

            // Air assist control
            if air_assist && !air_assist_active {
                out.push_str(&format!("{}\n", self.config.air_assist_on_cmd));
                air_assist_active = true;
            } else if !air_assist && air_assist_active {
                out.push_str(&format!("{}\n", self.config.air_assist_off_cmd));
                air_assist_active = false;
            }

            let map_pt = |p: &crate::geometry::Point2D| -> (f64, f64) {
                let x = if self.config.mirror_x {
                    (self.config.bed_width - p.x).clamp(0.0, self.config.bed_width)
                } else {
                    p.x
                };
                let y = if self.config.mirror_y {
                    (self.config.bed_height - p.y).clamp(0.0, self.config.bed_height)
                } else {
                    p.y
                };
                (x, y)
            };

            for pass in 0..passes {
                if z_step.abs() > 1e-4 {
                    z_curr -= z_step;
                    out.push_str(&format!("G0 Z{:.3}\n", z_curr));
                }

                out.push_str(&format!("; Pass {}/{} on Layer {}\n", pass + 1, passes, path.layer_index));

                // Rapid move to start
                let (x0, y0) = map_pt(&pts[0]);
                out.push_str(&format!("G0 X{:.3} Y{:.3}\n", x0, y0));

                // Start laser
                out.push_str(&format!("{} S{:.1}\n", laser_mode_cmd, s_val));

                // Cut along polyline
                for pt in &pts[1..] {
                    let (xi, yi) = map_pt(pt);
                    out.push_str(&format!("G1 X{:.3} Y{:.3} F{:.1}\n", xi, yi, speed_mm_min));
                }

                // Close loop if needed
                if path.polyline.is_closed && pts.len() > 2 {
                    let (x0, y0) = map_pt(&pts[0]);
                    out.push_str(&format!("G1 X{:.3} Y{:.3} F{:.1}\n", x0, y0, speed_mm_min));
                }

                // Laser off
                out.push_str("M5 ; Laser off\n");
            }
        }

        // Footer
        if air_assist_active {
            out.push_str(&format!("{}\n", self.config.air_assist_off_cmd));
        }
        out.push_str("M5 ; Final laser off\n");
        out.push_str("G0 X0 Y0 ; Return home\n");
        out.push_str("M2 ; End of program\n");

        out
    }

    /// Generates a low-power framing bounding box routine for workpiece alignment
    pub fn generate_framing(&self, doc: &Document) -> String {
        let b = doc.bounds();
        let mut out = String::new();
        out.push_str("; Framing Bounding Box Preview\n");
        out.push_str("G21 G90\n");
        out.push_str(&format!("G0 F{:.1}\n", self.config.rapid_speed));
        out.push_str(&format!("G0 X{:.3} Y{:.3}\n", b.min_x, b.min_y));
        out.push_str("M3 S5 ; Low power 0.5% laser pointer\n");
        out.push_str(&format!("G1 X{:.3} Y{:.3} F3000\n", b.max_x, b.min_y));
        out.push_str(&format!("G1 X{:.3} Y{:.3} F3000\n", b.max_x, b.max_y));
        out.push_str(&format!("G1 X{:.3} Y{:.3} F3000\n", b.min_x, b.max_y));
        out.push_str(&format!("G1 X{:.3} Y{:.3} F3000\n", b.min_x, b.min_y));
        out.push_str("M5 ; Laser off\n");
        out
    }
}
